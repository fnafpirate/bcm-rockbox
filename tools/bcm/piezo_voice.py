#!/usr/bin/env python3
"""
piezo_voice.py — Formant synthesiser that generates the click-speaker
                 chime samples embedded in bcm_piezo_voice_data.c.

Outputs a C source file with three arrays:
  piezo_voice_startup  — 100 ms ascending three-tone chime
  piezo_voice_shutdown — 100 ms descending three-tone chime
  piezo_voice_charge   — 50 ms single ping

Usage:
    python3 piezo_voice.py [--out bcm_piezo_voice_data.c]

Copyright (C) 2024 bcm-rockbox contributors
SPDX-License-Identifier: GPL-2.0-or-later
"""

import argparse
import math
import sys


RATE = 22050   # Hz


def gen_tone(freq_hz: float, dur_s: float,
             rate: int = RATE, fade_s: float = 0.01,
             amplitude: float = 0.5) -> list:
    """Generate a single pure tone with linear fade in/out."""
    n = int(dur_s * rate)
    fade_n = int(fade_s * rate)
    out = []
    for i in range(n):
        t = i / rate
        env = 1.0
        if i < fade_n and fade_n > 0:
            env = i / fade_n
        elif i > n - fade_n and fade_n > 0:
            env = (n - i) / fade_n
        v = int(env * amplitude * 32767.0 * math.sin(2.0 * math.pi * freq_hz * t))
        out.append(max(-32768, min(32767, v)))
    return out


def gen_chord(freqs, dur_s, rate=RATE, fade_s=0.01, amplitude=0.4):
    """Mix multiple tones together."""
    n = int(dur_s * rate)
    mixes = [gen_tone(f, dur_s, rate, fade_s, amplitude / len(freqs))
             for f in freqs]
    out = []
    for i in range(n):
        s = sum(m[i] for m in mixes)
        out.append(max(-32768, min(32767, s)))
    return out


def build_startup():
    # C5 E5 G5 ascending arpeggios
    c5 = gen_tone(523.25, 0.033, fade_s=0.005)
    e5 = gen_tone(659.25, 0.033, fade_s=0.005)
    g5 = gen_tone(784.00, 0.033, fade_s=0.005)
    samples = c5 + e5 + g5
    # Pad to exactly 2205 samples (100 ms)
    while len(samples) < 2205:
        samples.append(0)
    return samples[:2205]


def build_shutdown():
    # G5 E5 C5 descending
    g5 = gen_tone(784.00, 0.033, fade_s=0.005)
    e5 = gen_tone(659.25, 0.033, fade_s=0.005)
    c5 = gen_tone(523.25, 0.033, fade_s=0.005)
    samples = g5 + e5 + c5
    while len(samples) < 2205:
        samples.append(0)
    return samples[:2205]


def build_charge():
    # Single soft 880 Hz ping
    samples = gen_tone(880.0, 0.050, fade_s=0.010, amplitude=0.35)
    while len(samples) < 1102:
        samples.append(0)
    return samples[:1102]


def emit_array(out, name: str, samples: list):
    out.write(f"\nconst int16_t {name}[{len(samples)}] = {{\n")
    for i, v in enumerate(samples):
        if i % 16 == 0:
            out.write("    ")
        out.write(str(v))
        if i < len(samples) - 1:
            out.write(", ")
        if (i + 1) % 16 == 0:
            out.write("\n")
    out.write("\n};\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                   formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default="bcm_piezo_voice_data.c",
                        help="Output C source file")
    args = parser.parse_args()

    startup  = build_startup()
    shutdown = build_shutdown()
    charge   = build_charge()

    with open(args.out, "w") as f:
        f.write("/* Auto-generated by piezo_voice.py — do not edit */\n")
        f.write("#include <stdint.h>\n")
        emit_array(f, "piezo_voice_startup",  startup)
        emit_array(f, "piezo_voice_shutdown", shutdown)
        emit_array(f, "piezo_voice_charge",   charge)

    print(f"Written {args.out}")
    print(f"  startup:  {len(startup)} samples ({len(startup)/RATE*1000:.0f} ms)")
    print(f"  shutdown: {len(shutdown)} samples ({len(shutdown)/RATE*1000:.0f} ms)")
    print(f"  charge:   {len(charge)} samples ({len(charge)/RATE*1000:.0f} ms)")


if __name__ == "__main__":
    main()
